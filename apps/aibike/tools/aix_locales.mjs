export function resolveAixVariant(argv = []) {
  const args = [...argv];
  const requested = new Set();
  if (args.includes('--cn')) requested.add('cn');
  if (args.includes('--ja')) requested.add('ja');
  if (args.includes('--en')) requested.add('en');
  for (const raw of args.filter((arg) => String(arg).startsWith('--locale='))) {
    const locale = String(raw).slice('--locale='.length);
    if (locale === 'zh-CN') requested.add('cn');
    else if (locale === 'ja-JP') requested.add('ja');
    else if (locale === 'en-US') requested.add('en');
    else throw new Error(`Unsupported AIX locale argument: ${raw}`);
  }
  if (requested.size > 1) {
    throw new Error(
      `Conflicting AIX locale arguments; select exactly one: ${[...requested].join(', ')}`,
    );
  }
  return AIX_VARIANTS[[...requested][0] || 'cn'];
}

export function outputArgument(argv = []) {
  return argv.find((arg) => !String(arg).startsWith('--')) || null;
}

export function localizeJapaneseText(value) {
  let text = String(value ?? '');
  for (const [from, to] of [...JA_TEXT_REPLACEMENTS]
    .sort((left, right) => right[0].length - left[0].length)) {
    if (text.includes(from)) text = text.split(from).join(to);
  }
  return text;
}

