function visiblePageTemplate(value) {
  const match = String(value ?? '').match(/<page\b[^>]*>([\s\S]*?)<\/page>/i);
  return match ? match[1] : '';
}

function withoutSourceComments(value) {
  return String(value ?? '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
}

function withoutRegexLiterals(value) {
  // Locale purity concerns display/prompt strings, not multilingual safety
  // regexes. Requiring a regex-like token to follow an expression delimiter
  // avoids stripping the slash-separated copy used by HUD source labels.
  return String(value ?? '').replace(
    /(^\s*|[=(:,;!\[{}]\s*)\/(?:\\.|[^/\\\r\n])+\/[dgimsuvy]*/gm,
    '$1',
  );
}

export function assertEnglishRuntimeCopy(root) {
  const home = fs.readFileSync(path.join(root, 'pages/index/index.ink'), 'utf8');
  const ride = fs.readFileSync(path.join(root, 'pages/ride_hud/index.ink'), 'utf8');
  const runtimeText = ENGLISH_LOCALIZED_FILES
    .filter((rel) => fs.existsSync(path.join(root, rel)))
    .map((rel) => fs.readFileSync(path.join(root, rel), 'utf8'))
    .join('\n');
  const markerText = `${home}\n${ride}\n${runtimeText}`;
  const missing = ENGLISH_REQUIRED_MARKERS.filter((marker) => !markerText.includes(marker));
  if (missing.length) throw new Error(`English runtime copy is missing: ${missing.join(', ')}`);

  const visibleTemplates = `${visiblePageTemplate(home)}\n${visiblePageTemplate(ride)}`;
  const visibleHan = [...new Set(visibleTemplates.match(/[\u3400-\u9fff]+/g) || [])];
  if (visibleHan.length) {
    throw new Error(`English page templates still contain Chinese UI copy: ${visibleHan.join(', ')}`);
  }

  const copyText = withoutSourceComments(markerText);
  const forbidden = ENGLISH_FORBIDDEN_UI_COPY.filter((copy) => copyText.includes(copy));
  if (forbidden.length) {
    throw new Error(`English runtime still contains Chinese UI copy: ${forbidden.join(', ')}`);
  }


  const executableRuntimeText = ENGLISH_LOCALIZED_FILES
    .filter((rel) => rel.startsWith('pages/') || rel.startsWith('lib/'))
    .map((rel) => fs.readFileSync(path.join(root, rel), 'utf8'))
    .join('\n');
  const cjkResidue = [...new Set(
    withoutRegexLiterals(withoutSourceComments(executableRuntimeText))
      .match(/[\u3040-\u30ff\u3400-\u9fff]+/g) || [],
  )];
  if (cjkResidue.length) {
    throw new Error(`English runtime still contains CJK copy: ${cjkResidue.join(', ')}`);
  }

  const advice = fs.readFileSync(path.join(root, 'lib/ride_ai_advice.js'), 'utf8');
  if (!advice.includes('RIDE_AI_ADVICE_MAX_CHARS = 80')
      || !advice.includes('/[A-Za-z]/')
      || !advice.includes('one English sentence')) {
    throw new Error('English AI ride advice must use the English prompt, 80-character cap, and Latin-script acceptance gate');
  }
}

export function assertJapaneseRuntimeCopy(root) {
  const home = fs.readFileSync(path.join(root, 'pages/index/index.ink'), 'utf8');
  const ride = fs.readFileSync(path.join(root, 'pages/ride_hud/index.ink'), 'utf8');
  const runtimeText = JAPANESE_LOCALIZED_FILES
    .filter((rel) => fs.existsSync(path.join(root, rel)))
    .map((rel) => fs.readFileSync(path.join(root, rel), 'utf8'))
    .join('\n');
  const markerText = `${home}\n${ride}\n${runtimeText}`;
  const executableRuntimeText = JAPANESE_LOCALIZED_FILES
    .filter((rel) => (rel.startsWith('pages/') || rel.startsWith('lib/'))
      && fs.existsSync(path.join(root, rel)))
    .map((rel) => fs.readFileSync(path.join(root, rel), 'utf8'))
    .join('\n');
  const missing = JAPANESE_REQUIRED_MARKERS.filter((marker) => !markerText.includes(marker));
  if (missing.length) throw new Error(`Japanese runtime copy is missing: ${missing.join(', ')}`);
  const forbidden = JAPANESE_FORBIDDEN_UI_COPY.filter(
    (copy) => executableRuntimeText.includes(copy),
  );
  if (forbidden.length) {
    throw new Error(`Japanese runtime still contains Chinese UI copy: ${forbidden.join(', ')}`);
  }

  const simplifiedResidue = japaneseVisibleCopyIssues(
    withoutRegexLiterals(withoutSourceComments(executableRuntimeText)),
  );
  if (simplifiedResidue.length) {
    throw new Error(
      `Japanese runtime still contains simplified-Chinese copy: ${simplifiedResidue.join(', ')}`,
    );
  }
}

export function localizeJapaneseStage(root) {
  for (const rel of JAPANESE_LOCALIZED_FILES) {
    const target = path.join(root, rel);
    if (!fs.existsSync(target)) throw new Error(`Japanese locale input is missing: ${rel}`);
    const before = fs.readFileSync(target, 'utf8');
    const after = localizeJapaneseText(before);
    if (after === before && /[一-龯]/.test(before)) {
      throw new Error(`Japanese locale made no change to user-copy file: ${rel}`);
    }
    fs.writeFileSync(target, after, 'utf8');
  }

  const pkgPath = path.join(root, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  pkg.description = JAPANESE_STORE_DESCRIPTION;
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');

  assertJapaneseRuntimeCopy(root);
}

